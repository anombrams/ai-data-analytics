@dataclass
class ExportConfig:
    """Configuration for exports"""
    title: str = "Data Dashboard Report"
    subtitle: str = ""
    author: str = "AI Data Portal"
    date: str = ""
    logo_path: Optional[str] = None
    primary_color: Tuple[int, int, int] = (30, 136, 229)  # Blue
    secondary_color: Tuple[int, int, int] = (66, 66, 66)  # Dark gray


class ChartExporter:
    """Handles converting Plotly charts to images"""

    @staticmethod
    def chart_to_image(fig: go.Figure, width: int = 800, height: int = 500, scale: float = 2.0) -> Optional[bytes]:
        """
        Convert Plotly figure to PNG image bytes

        Args:
            fig: Plotly figure
            width: Image width in pixels
            height: Image height in pixels
            scale: Scale factor for higher resolution

        Returns:
            PNG image as bytes, or None if conversion fails
        """
        try:
            # Update layout for clean export
            fig.update_layout(
                paper_bgcolor='white',
                plot_bgcolor='white',
                margin=dict(l=40, r=40, t=60, b=40)
            )

            # Convert to image bytes
            img_bytes = fig.to_image(
                format='png',
                width=width,
                height=height,
                scale=scale
            )
            return img_bytes

        except Exception as e:
            print(f"Error converting chart to image: {e}")
            return None

    @staticmethod
    def save_chart_to_file(fig: go.Figure, filepath: str, width: int = 800, height: int = 500) -> bool:
        """Save Plotly figure to image file"""
        try:
            fig.write_image(filepath, width=width, height=height, scale=2)
            return True
        except Exception as e:
            print(f"Error saving chart: {e}")
            return False


class PDFExporter(FPDF):
    """Custom PDF class for dashboard reports"""

    def __init__(self, config: ExportConfig):
        super().__init__()
        self.config = config
        self.set_auto_page_break(auto=True, margin=15)

    def header(self):
        """Page header"""
        self.set_font('Helvetica', 'B', 10)
        self.set_text_color(*self.config.secondary_color)
        self.cell(0, 10, self.config.title, 0, 0, 'L')
        self.ln(15)

    def footer(self):
        """Page footer"""
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f'Page {self.page_no()}', 0, 0, 'C')

    def create_cover_page(self):
        """Create cover page"""
        self.add_page()
        self.set_font('Helvetica', 'B', 32)
        self.set_text_color(*self.config.primary_color)

        # Title
        self.ln(60)
        self.cell(0, 20, self.config.title, 0, 1, 'C')

        # Subtitle
        if self.config.subtitle:
            self.set_font('Helvetica', '', 16)
            self.set_text_color(*self.config.secondary_color)
            self.cell(0, 10, self.config.subtitle, 0, 1, 'C')

        # Author and date
        self.ln(30)
        self.set_font('Helvetica', '', 12)
        self.set_text_color(100, 100, 100)

        if self.config.author:
            self.cell(0, 10, f"Generated by: {self.config.author}", 0, 1, 'C')

        if self.config.date:
            self.cell(0, 10, f"Date: {self.config.date}", 0, 1, 'C')

    def add_kpi_section(self, kpis: List[Dict[str, Any]]):
        """Add KPI section"""
        self.add_page()
        self.set_font('Helvetica', 'B', 18)
        self.set_text_color(*self.config.primary_color)
        self.cell(0, 15, 'Key Performance Indicators', 0, 1, 'L')

        self.ln(5)

        # KPI boxes
        box_width = 45
        margin = 5
        x_start = 10

        for i, kpi in enumerate(kpis[:4]):  # Max 4 KPIs per row
            x = x_start + (box_width + margin) * i

            # Box background (simulated with rectangle)
            self.set_fill_color(245, 245, 245)
            self.rect(x, self.get_y(), box_width, 30, 'F')

            # KPI title
            self.set_xy(x + 2, self.get_y() + 3)
            self.set_font('Helvetica', '', 9)
            self.set_text_color(100, 100, 100)
            self.cell(box_width - 4, 5, str(kpi.get('title', ''))[:20], 0, 0, 'L')

            # KPI value
            self.set_xy(x + 2, self.get_y() + 8)
            self.set_font('Helvetica', 'B', 14)
            self.set_text_color(*self.config.primary_color)

            value = kpi.get('value', 0)
            if isinstance(value, float):
                value_str = f"{value:,.2f}"
            elif isinstance(value, int):
                value_str = f"{value:,}"
            else:
                value_str = str(value)

            self.cell(box_width - 4, 10, value_str[:15], 0, 0, 'L')

        self.ln(40)

    def add_chart_image(self, image_bytes: bytes, title: str = "", width: int = 180):
        """Add chart image to PDF"""
        if not image_bytes:
            return

        # Save to temp file
        with tempfile.NamedTemporaryFile(suffix='.png', delete=False) as tmp:
            tmp.write(image_bytes)
            tmp_path = tmp.name

        try:
            # Check if we need a new page
            if self.get_y() > 180:
                self.add_page()

            # Add title if provided
            if title:
                self.set_font('Helvetica', 'B', 12)
                self.set_text_color(*self.config.secondary_color)
                self.cell(0, 10, title, 0, 1, 'L')

            # Add image
            self.image(tmp_path, x=15, w=width)
            self.ln(10)

        finally:
            # Clean up temp file
            os.unlink(tmp_path)

    def add_insights_section(self, insights: str):
        """Add insights text section"""
        if not insights:
            return

        self.add_page()
        self.set_font('Helvetica', 'B', 18)
        self.set_text_color(*self.config.primary_color)
        self.cell(0, 15, 'Insights & Analysis', 0, 1, 'L')

        self.ln(5)
        self.set_font('Helvetica', '', 11)
        self.set_text_color(*self.config.secondary_color)
        self.multi_cell(0, 7, insights)

    def add_data_summary(self, df: pd.DataFrame):
        """Add data summary table"""
        self.add_page()
        self.set_font('Helvetica', 'B', 18)
        self.set_text_color(*self.config.primary_color)
        self.cell(0, 15, 'Data Summary', 0, 1, 'L')

        self.ln(5)

        # Basic stats
        self.set_font('Helvetica', '', 11)
        self.set_text_color(*self.config.secondary_color)
        self.cell(0, 7, f"Total Records: {len(df):,}", 0, 1, 'L')
        self.cell(0, 7, f"Total Columns: {len(df.columns)}", 0, 1, 'L')
        self.cell(0, 7, f"Missing Values: {df.isna().sum().sum():,}", 0, 1, 'L')

        self.ln(10)

        # Column summary table
        self.set_font('Helvetica', 'B', 10)
        self.cell(60, 8, 'Column', 1, 0, 'L')
        self.cell(40, 8, 'Type', 1, 0, 'L')
        self.cell(30, 8, 'Unique', 1, 0, 'R')
        self.cell(30, 8, 'Missing', 1, 1, 'R')

        self.set_font('Helvetica', '', 9)
        for col in df.columns[:20]:  # Limit to 20 columns
            self.cell(60, 7, str(col)[:30], 1, 0, 'L')
            self.cell(40, 7, str(df[col].dtype), 1, 0, 'L')
            self.cell(30, 7, str(df[col].nunique()), 1, 0, 'R')
            self.cell(30, 7, str(df[col].isna().sum()), 1, 1, 'R')


class PowerPointExporter:
    """Export dashboard to PowerPoint"""

    def __init__(self, config: ExportConfig):
        self.config = config
        self.prs = Presentation()
        self.prs.slide_width = Inches(13.333)  # 16:9 aspect ratio
        self.prs.slide_height = Inches(7.5)

    def _get_rgb_color(self, color_tuple: Tuple[int, int, int]) -> RGBColor:
        """Convert tuple to RGBColor"""
        return RGBColor(color_tuple[0], color_tuple[1], color_tuple[2])

    def create_title_slide(self):
        """Create title slide"""
        slide_layout = self.prs.slide_layouts[6]  # Blank layout
        slide = self.prs.slides.add_slide(slide_layout)

        # Title
        title_box = slide.shapes.add_textbox(Inches(0.5), Inches(2.5), Inches(12.33), Inches(1.5))
        title_frame = title_box.text_frame
        title_para = title_frame.paragraphs[0]
        title_para.text = self.config.title
        title_para.font.size = Pt(44)
        title_para.font.bold = True
        title_para.font.color.rgb = self._get_rgb_color(self.config.primary_color)
        title_para.alignment = PP_ALIGN.CENTER

        # Subtitle
        if self.config.subtitle:
            subtitle_box = slide.shapes.add_textbox(Inches(0.5), Inches(4), Inches(12.33), Inches(0.8))
            sub_frame = subtitle_box.text_frame
            sub_para = sub_frame.paragraphs[0]
            sub_para.text = self.config.subtitle
            sub_para.font.size = Pt(24)
            sub_para.font.color.rgb = self._get_rgb_color(self.config.secondary_color)
            sub_para.alignment = PP_ALIGN.CENTER

        # Author and date
        info_box = slide.shapes.add_textbox(Inches(0.5), Inches(6), Inches(12.33), Inches(0.8))
        info_frame = info_box.text_frame
        info_para = info_frame.paragraphs[0]
        info_text = []
        if self.config.author:
            info_text.append(f"Generated by: {self.config.author}")
        if self.config.date:
            info_text.append(self.config.date)
        info_para.text = " | ".join(info_text)
        info_para.font.size = Pt(14)
        info_para.font.color.rgb = RGBColor(128, 128, 128)
        info_para.alignment = PP_ALIGN.CENTER

    def create_kpi_slide(self, kpis: List[Dict[str, Any]]):
        """Create KPI summary slide"""
        slide_layout = self.prs.slide_layouts[6]  # Blank
        slide = self.prs.slides.add_slide(slide_layout)

        # Title
        title_box = slide.shapes.add_textbox(Inches(0.5), Inches(0.3), Inches(12.33), Inches(0.8))
        title_frame = title_box.text_frame
        title_para = title_frame.paragraphs[0]
        title_para.text = "Key Performance Indicators"
        title_para.font.size = Pt(32)
        title_para.font.bold = True
        title_para.font.color.rgb = self._get_rgb_color(self.config.primary_color)

        # KPI boxes
        kpi_count = min(len(kpis), 5)
        box_width = Inches(2.3)
        box_height = Inches(1.5)
        start_x = Inches(0.5)
        y_pos = Inches(2)
        gap = Inches(0.3)

        for i, kpi in enumerate(kpis[:kpi_count]):
            x_pos = start_x + i * (box_width + gap)

            # KPI box
            shape = slide.shapes.add_shape(
                1,  # Rectangle
                x_pos, y_pos,
                box_width, box_height
            )
            shape.fill.solid()
            shape.fill.fore_color.rgb = RGBColor(245, 245, 245)
            shape.line.fill.background()

            # KPI title
            title_tb = slide.shapes.add_textbox(
                x_pos + Inches(0.1), y_pos + Inches(0.1),
                box_width - Inches(0.2), Inches(0.4)
            )
            tf = title_tb.text_frame
            tf.paragraphs[0].text = str(kpi.get('title', ''))[:20]
            tf.paragraphs[0].font.size = Pt(12)
            tf.paragraphs[0].font.color.rgb = RGBColor(100, 100, 100)

            # KPI value
            value = kpi.get('value', 0)
            if isinstance(value, float):
                value_str = f"{value:,.2f}"
            elif isinstance(value, int):
                value_str = f"{value:,}"
            else:
                value_str = str(value)

            value_tb = slide.shapes.add_textbox(
                x_pos + Inches(0.1), y_pos + Inches(0.5),
                box_width - Inches(0.2), Inches(0.8)
            )
            vf = value_tb.text_frame
            vf.paragraphs[0].text = value_str[:15]
            vf.paragraphs[0].font.size = Pt(28)
            vf.paragraphs[0].font.bold = True
            vf.paragraphs[0].font.color.rgb = self._get_rgb_color(self.config.primary_color)

    def create_chart_slide(self, image_bytes: bytes, title: str = "", description: str = ""):
        """Create slide with chart image"""
        if not image_bytes:
            return

        slide_layout = self.prs.slide_layouts[6]  # Blank
        slide = self.prs.slides.add_slide(slide_layout)

        # Title
        if title:
            title_box = slide.shapes.add_textbox(Inches(0.5), Inches(0.3), Inches(12.33), Inches(0.6))
            title_frame = title_box.text_frame
            title_para = title_frame.paragraphs[0]
            title_para.text = title
            title_para.font.size = Pt(28)
            title_para.font.bold = True
            title_para.font.color.rgb = self._get_rgb_color(self.config.secondary_color)

        # Chart image
        with tempfile.NamedTemporaryFile(suffix='.png', delete=False) as tmp:
            tmp.write(image_bytes)
            tmp_path = tmp.name

        try:
            slide.shapes.add_picture(
                tmp_path,
                Inches(0.5), Inches(1.2),
                width=Inches(12.33), height=Inches(5.5)
            )
        finally:
            os.unlink(tmp_path)

        # Description
        if description:
            desc_box = slide.shapes.add_textbox(Inches(0.5), Inches(6.8), Inches(12.33), Inches(0.5))
            desc_frame = desc_box.text_frame
            desc_para = desc_frame.paragraphs[0]
            desc_para.text = description
            desc_para.font.size = Pt(12)
            desc_para.font.color.rgb = RGBColor(100, 100, 100)
            desc_para.alignment = PP_ALIGN.CENTER

    def create_insights_slide(self, insights: str):
        """Create insights slide"""
        if not insights:
            return

        slide_layout = self.prs.slide_layouts[6]  # Blank
        slide = self.prs.slides.add_slide(slide_layout)

        # Title
        title_box = slide.shapes.add_textbox(Inches(0.5), Inches(0.3), Inches(12.33), Inches(0.8))
        title_frame = title_box.text_frame
        title_para = title_frame.paragraphs[0]
        title_para.text = "Insights & Analysis"
        title_para.font.size = Pt(32)
        title_para.font.bold = True
        title_para.font.color.rgb = self._get_rgb_color(self.config.primary_color)

        # Insights text
        text_box = slide.shapes.add_textbox(Inches(0.5), Inches(1.5), Inches(12.33), Inches(5))
        text_frame = text_box.text_frame
        text_frame.word_wrap = True

        # Split insights into paragraphs
        paragraphs = insights.split('\n')
        for i, para_text in enumerate(paragraphs):
            if i == 0:
                p = text_frame.paragraphs[0]
            else:
                p = text_frame.add_paragraph()

            p.text = para_text
            p.font.size = Pt(18)
            p.font.color.rgb = self._get_rgb_color(self.config.secondary_color)
            p.space_after = Pt(12)

    def save(self, filepath: str) -> bool:
        """Save presentation to file"""
        try:
            self.prs.save(filepath)
            return True
        except Exception as e:
            print(f"Error saving PowerPoint: {e}")
            return False

    def get_bytes(self) -> bytes:
        """Get presentation as bytes"""
        buffer = io.BytesIO()
        self.prs.save(buffer)
        return buffer.getvalue()


class Exporter:
    """Main exporter class for PDF and PPTX"""

    def __init__(self, config: Optional[ExportConfig] = None):
        self.config = config or ExportConfig()

    def export_to_pdf(
        self,
        df: pd.DataFrame,
        figures: List[go.Figure],
        kpis: List[Dict[str, Any]],
        insights: str = "",
        filename: str = "dashboard_report.pdf"
    ) -> bytes:
        """
        Export dashboard to PDF

        Args:
            df: DataFrame with data
            figures: List of Plotly figures
            kpis: List of KPI dictionaries
            insights: Insights text
            filename: Output filename

        Returns:
            PDF file as bytes
        """
        pdf = PDFExporter(self.config)

        # Cover page
        pdf.create_cover_page()

        # KPI section
        if kpis:
            pdf.add_kpi_section(kpis)

        # Charts
        for i, fig in enumerate(figures):
            # Convert chart to image
            img_bytes = ChartExporter.chart_to_image(fig)
            if img_bytes:
                title = fig.layout.title.text if fig.layout.title and fig.layout.title.text else f"Chart {i+1}"
                pdf.add_chart_image(img_bytes, title=title)

        # Insights
        if insights:
            pdf.add_insights_section(insights)

        # Data summary
        pdf.add_data_summary(df)

        # Output
        buffer = io.BytesIO()
        pdf.output(buffer)
        return buffer.getvalue()

    def export_to_pptx(
        self,
        figures: List[go.Figure],
        kpis: List[Dict[str, Any]],
        insights: str = "",
        chart_descriptions: Optional[List[str]] = None
    ) -> bytes:
        """
        Export dashboard to PowerPoint

        Args:
            figures: List of Plotly figures
            kpis: List of KPI dictionaries
            insights: Insights text
            chart_descriptions: Optional descriptions for each chart

        Returns:
            PPTX file as bytes
        """
        pptx = PowerPointExporter(self.config)

        # Title slide
        pptx.create_title_slide()

        # KPI slide
        if kpis:
            pptx.create_kpi_slide(kpis)

        # Chart slides
        for i, fig in enumerate(figures):
            img_bytes = ChartExporter.chart_to_image(fig, width=1200, height=700)
            if img_bytes:
                title = fig.layout.title.text if fig.layout.title and fig.layout.title.text else f"Chart {i+1}"
                desc = chart_descriptions[i] if chart_descriptions and i < len(chart_descriptions) else ""
                pptx.create_chart_slide(img_bytes, title=title, description=desc)

        # Insights slide
        if insights:
            pptx.create_insights_slide(insights)

        return pptx.get_bytes()

    def export_dashboard(
        self,
        dashboard_builder,
        df: pd.DataFrame,
        format: str = 'pdf'
    ) -> bytes:
        """
        Export dashboard from DashboardBuilder

        Args:
            dashboard_builder: DashboardBuilder instance with config
            df: DataFrame
            format: 'pdf' or 'pptx'

        Returns:
            File bytes
        """
        config = dashboard_builder.config
        if not config:
            raise ValueError("Dashboard has no configuration")

        # Get figures
        figures = dashboard_builder.get_all_figures()

        # Get KPIs as dicts
        kpis = [
            {'title': k.title, 'value': k.value, 'delta': k.delta}
            for k in config.kpis
        ]

        # Chart descriptions
        descriptions = [c.description for c in config.charts]

        # Update export config
        self.config.title = config.title

        if format.lower() == 'pdf':
            return self.export_to_pdf(df, figures, kpis, config.insights)
        elif format.lower() in ('pptx', 'powerpoint'):
            return self.export_to_pptx(figures, kpis, config.insights, descriptions)
        else:
            raise ValueError(f"Unsupported format: {format}")


def render_export_section(dashboard_builder, df: pd.DataFrame):
    """Render export options in Streamlit"""
    import streamlit as st
    from datetime import datetime

    st.subheader("Export Dashboard")

    if not dashboard_builder or not dashboard_builder.config:
        st.warning("Generate a dashboard first before exporting.")
        return

    # Export options
    col1, col2, col3 = st.columns([2, 1, 1])

    with col1:
        report_title = st.text_input(
            "Report Title",
            value=dashboard_builder.config.title
        )

    with col2:
        author = st.text_input("Author", value="AI Data Portal")

    with col3:
        include_date = st.checkbox("Include Date", value=True)

    # Create exporter
    export_config = ExportConfig(
        title=report_title,
        author=author,
        date=datetime.now().strftime("%Y-%m-%d") if include_date else ""
    )
    exporter = Exporter(export_config)

    # Export buttons
    col1, col2, col3 = st.columns(3)

    with col1:
        if st.button("Export to PDF", type="primary", use_container_width=True):
            with st.spinner("Generating PDF..."):
                try:
                    pdf_bytes = exporter.export_dashboard(dashboard_builder, df, 'pdf')
                    st.download_button(
                        "Download PDF",
                        pdf_bytes,
                        f"{report_title.replace(' ', '_')}.pdf",
                        "application/pdf",
                        use_container_width=True
                    )
                    st.success("PDF generated!")
                except Exception as e:
                    st.error(f"Error generating PDF: {e}")

    with col2:
        if st.button("Export to PowerPoint", type="primary", use_container_width=True):
            with st.spinner("Generating PowerPoint..."):
                try:
                    pptx_bytes = exporter.export_dashboard(dashboard_builder, df, 'pptx')
                    st.download_button(
                        "Download PPTX",
                        pptx_bytes,
                        f"{report_title.replace(' ', '_')}.pptx",
                        "application/vnd.openxmlformats-officedocument.presentationml.presentation",
                        use_container_width=True
                    )
                    st.success("PowerPoint generated!")
                except Exception as e:
                    st.error(f"Error generating PowerPoint: {e}")

    with col3:
        if st.button("Save Dashboard Config", use_container_width=True):
            try:
                import json
                config_dict = {
                    'title': dashboard_builder.config.title,
                    'layout': dashboard_builder.config.layout,
                    'insights': dashboard_builder.config.insights,
                    'kpis': [
                        {'title': k.title, 'value': k.value}
                        for k in dashboard_builder.config.kpis
                    ],
                    'charts': [
                        {'type': c.chart_type, 'title': c.title, 'columns': c.columns}
                        for c in dashboard_builder.config.charts
                    ]
                }
                config_json = json.dumps(config_dict, indent=2, default=str)
                st.download_button(
                    "Download Config JSON",
                    config_json,
                    "dashboard_config.json",
                    "application/json",
                    use_container_width=True
                )
            except Exception as e:
                st.error(f"Error saving config: {e}")
